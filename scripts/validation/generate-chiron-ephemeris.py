#!/usr/bin/env python3
"""Generate an offline, versioned Chiron ephemeris (pyswisseph 2.10.3.2).

Usage: python scripts/validation/generate-chiron-ephemeris.py --ephe /path/to/ephe
Requires the verified manifest from the Swiss audit. No network access.
The table contains physical heliocentric J2000 Cartesian states, not corrections
fitted to observed errors. Runtime interpolation is independent of Swiss code.
"""
import argparse
import hashlib
import json
import math
import importlib.metadata
from pathlib import Path
import swisseph as swe

ROOT = Path(__file__).resolve().parents[2]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ephe', type=Path, required=True)
    args = parser.parse_args()
    if importlib.metadata.version('pyswisseph') != '2.10.3.2' or swe.version != '2.10.03':
        raise ValueError('Generation requires pyswisseph 2.10.3.2 / Swiss 2.10.03')
    manifest = json.loads((args.ephe / 'manifest.json').read_text())
    for item in manifest['files']:
        if hashlib.sha256((args.ephe / item['name']).read_bytes()).hexdigest() != item['sha256']:
            raise ValueError('Ephemeris hash mismatch: ' + item['name'])
    swe.set_ephe_path(str(args.ephe.resolve()))
    start = swe.julday(1929, 11, 1, 0)
    step = 16.0
    count = math.ceil((swe.julday(2041, 3, 1, 0) - start) / step) + 1
    flags = swe.FLG_SWIEPH | swe.FLG_HELCTR | swe.FLG_J2000 | swe.FLG_TRUEPOS | swe.FLG_NONUT | swe.FLG_XYZ | swe.FLG_SPEED
    states = []
    for i in range(count):
        state, returned = swe.calc(start + i * step, swe.CHIRON, flags)
        if returned & 7 != swe.FLG_SWIEPH or not all(map(math.isfinite, state)):
            raise ValueError('Invalid Swiss result or fallback')
        states.append(state)
    target = ROOT / 'core/src/astronomy/chiron_ephemeris.rs'
    text = '// Generated by scripts/validation/generate-chiron-ephemeris.py; do not edit.\n'
    text += '// Swiss Ephemeris / Astrodienst AG data, distributed under AGPL-3.0-or-later.\n'
    text += '// Physical heliocentric J2000 states: x,y,z [AU], vx,vy,vz [AU/day], TT.\n'
    text += f'const EPHE_START: f64 = {start};\nconst EPHE_STEP: f64 = {step};\n'
    text += '#[rustfmt::skip]\nconst EPHE_STATES: &[[f64; 6]] = &[\n'
    text += ''.join('    [' + ', '.join(format(x, '.17e') for x in row) + '],\n' for row in states)
    text += '];\n'
    target.write_text(text)
    info = dict(swissVersion=swe.version, flags=flags, frame='heliocentric mean ecliptic J2000',
                timeScale='TT', startJD=start, endJD=start+(count-1)*step, stepDays=step,
                count=count, interpolation='cubic Hermite, position and velocity',
                ephemerisManifest=manifest, license='AGPL-3.0-or-later',
                generatedSha256=hashlib.sha256(text.encode()).hexdigest())
    provenance = ROOT / 'core/data/chiron-ephemeris.json'
    provenance.parent.mkdir(parents=True, exist_ok=True)
    provenance.write_text(json.dumps(info, indent=2)+'\n')
    print(f'Generated {count} Chiron states in {target}')

if __name__ == '__main__':
    main()
