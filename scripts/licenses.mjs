import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = fileURLToPath(new URL('../', import.meta.url));
const target = 'wasm32-unknown-unknown';
const destination = join(directory, 'THIRD-PARTY-NOTICES.txt');

function cargo(args) {
  return execFileSync('cargo', args, { cwd: directory, encoding: 'utf8' });
}

function buildPackages() {
  const metadata = JSON.parse(cargo(['metadata', '--locked', '--format-version=1', '--filter-platform', target]));
  const tree = cargo(['tree', '--locked', '--target', target, '--edges', 'normal,build',
    '--package', 'celestial-wasm', '--prefix', 'none', '--no-dedupe', '--format', '{p}']);
  const keys = new Set([...tree.matchAll(/^(\S+) v(\S+)/gm)].map(match => `${match[1]}@${match[2]}`));
  return metadata.packages.filter(pkg => pkg.source?.startsWith('registry+') && keys.has(`${pkg.name}@${pkg.version}`))
    .sort((a, b) => a.name.localeCompare(b.name, 'en'));
}

async function packageNotices(pkg) {
  const source = dirname(pkg.manifest_path);
  const files = (await readdir(source)).filter(name => /^(LICENSE|COPYING|NOTICE|COPYRIGHT)/i.test(name)).sort();
  if (!files.length) throw new Error(`No upstream license notices found: ${pkg.name}@${pkg.version}`);
  let text = `\n=== ${pkg.name}@${pkg.version} ===\nDeclared license: ${pkg.license}\nRegistry: ${pkg.source}\nRepository: ${pkg.repository ?? '(not declared)'}\n`;
  for (const file of files) {
    const original = await readFile(join(source, file), 'utf8');
    text += `\n--- BEGIN ${file} ---\n${original}\n--- END ${file} ---\n`;
  }
  return text;
}

const packages = buildPackages();
const lockHash = createHash('sha256').update(await readFile(join(directory, 'Cargo.lock'))).digest('hex');
let text = `Third-party Rust dependency notices\n\nCelestial retains its original AGPL-3.0-or-later licensing; see LICENSE and NOTICE.\nThe texts below reproduce the upstream license and copyright files of the registry\ncrates in the celestial-wasm normal/build dependency graph, including host build\ntools and procedural macros used by that build.\n\nTarget: ${target}\nBuild: cargo build --locked -p celestial-wasm --release --target ${target}\nCargo.lock SHA256: ${lockHash}\nCrates: ${packages.length}\nGenerated by: node scripts/licenses.mjs\n`;
for (const pkg of packages) text += await packageNotices(pkg);

if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== text) throw new Error('Third-party notices are stale; run npm run licenses');
  console.log(`Verified third-party notices for ${packages.length} locked Rust build dependencies.`);
} else {
  await writeFile(destination, text);
  console.log(`Generated third-party notices for ${packages.length} locked Rust build dependencies.`);
}
