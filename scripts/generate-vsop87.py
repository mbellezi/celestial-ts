#!/usr/bin/env python3
"""Reproduce VSOP87D Rust tables from unmodified IMCCE distribution files.

Usage: python3 scripts/generate-vsop87.py /path/to/vsop87
Source: https://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87D.{mer,...}
A, B, C are copied as decimal strings (radians, radians, AU; tau millennia).
For |tau| <= 0.1 (1900–2100), omit terms greedily in ascending order of
|A| * 0.1**order until their sum reaches 1e-7 per variable. By |cos| <= 1,
this bounds each coordinate's absolute truncation error at 1e-7 rad / AU.
Full original series remain available outside this interval. This is an
absolute analytic bound relative to VSOP87D, not a fit to modern ephemerides.
"""
import hashlib
import pathlib
import re
import sys

names = [('MERCURY','mer'),('VENUS','ven'),('EARTH','ear'),('MARS','mar'),('JUPITER','jup'),('SATURN','sat'),('URANUS','ura'),('NEPTUNE','nep')]
source = pathlib.Path(sys.argv[1])
out = ['// Generated by scripts/generate-vsop87.py; do not edit.', '// Source: https://ftp.imcce.fr/pub/ephem/planets/vsop87/', '// Native amplitudes; no implicit scale factor.', '']
for name, ext in names:
    path = source / ('VSOP87D.'+ext)
    raw = path.read_bytes()
    out.append('// '+path.name+' SHA256 '+hashlib.sha256(raw).hexdigest())
    series = {}
    expected_counts = {}
    for line in raw.decode('ascii').splitlines():
        if 'VSOP87 VERSION' in line:
            m = re.search(r'VARIABLE\s+(\d).*\*T\*\*(\d)',line)
            var, order = map(int,m.groups())
            series[var,order] = []
            expected_counts[var,order] = int(re.search(r"(\d+)\s+TERM", line).group(1))
        else:
            a,b,c = line.split()[-3:]
            series[var,order].append((a,b,c))
    for key, expected in expected_counts.items():
        assert len(series[key]) == expected, (path, key, expected, len(series[key]))
    for var, letter in [(1,'L'),(2,'B'),(3,'R')]:
        terms = [(abs(float(term[0]))*0.1**order,order,i) for (v,order),values in series.items() if v==var for i,term in enumerate(values)]
        omitted = set()
        bound = 0.
        for weight,order,i in sorted(terms):
            if bound+weight > 1e-7: break
            bound += weight
            omitted.add((order,i))
        out.append(f'// {name} {letter}: omitted bound {bound:.17e}; retained {len(terms)-len(omitted)}/{len(terms)} terms.')
        for mode in ['FULL','FAST']:
            arrays=[]
            for (v,order),values in series.items():
                if v != var: continue
                array=f'{name}_{letter}{order}_{mode}'
                arrays.append(array)
                out.append(f'static {array}: &[Term] = &[')
                for i,(a,b,c) in enumerate(values):
                    if mode=='FAST' and (order,i) in omitted: continue
                    out.append(f'    Term({a}, {b}, {c}),')
                out.append('];')
            out.append(f'static {name}_{letter}_{mode}: &[&[Term]] = &[{", ".join(arrays)}];')
pathlib.Path('core/src/astronomy/vsop87_data.rs').write_text('\n'.join(out)+'\n')
